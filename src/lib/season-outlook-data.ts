// Helper functions for filtering and sorting
export function getOutlooksByLeague(
  outlooks: TeamSeasonOutlook[],
  league: LeagueId
): TeamSeasonOutlook[] {
  return outlooks.filter((t) => t.league === league);
}

export function filterOutlooks(
  outlooks: TeamSeasonOutlook[],
  league: LeagueId,
  tier: TierId | "all",
  searchQuery: string
): TeamSeasonOutlook[] {
  return outlooks.filter((t) => {
    if (t.league !== league) return false;
    if (tier !== "all" && t.tier !== tier) return false;
    if (searchQuery.trim().length > 0) {
      const q = searchQuery.toLowerCase();
      const matchTeam = t.team.toLowerCase().includes(q);
      const matchShort = t.shortName.toLowerCase().includes(q);
      const matchNotes = t.what_to_know.some((note) => note.toLowerCase().includes(q));
      if (!matchTeam && !matchShort && !matchNotes) return false;
    }
    return true;
  });
}

export type SortField = "composite" | "sharpmodels" | "elo" | "playoff_pct" | "team";

export function sortOutlooks(
  outlooks: TeamSeasonOutlook[],
  field: SortField,
  ascending: boolean = false
): TeamSeasonOutlook[] {
  return [...outlooks].sort((a, b) => {
    let diff = 0;
    if (field === "team") {
      diff = a.team.localeCompare(b.team);
    } else {
      diff = b[field] - a[field];
    }
    return ascending ? -diff : diff;
  });
}
